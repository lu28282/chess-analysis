"""Settings: schema-driven normalization, validation, and TOML (re)writing.

The TOML config file is the single source of truth. The web UI settings page
and the first-run setup wizard both write it through here: a partial payload is
overlaid onto the current file's values, normalized against the schema below,
validated by constructing a full AppConfig, and written atomically.
"""

from __future__ import annotations

import math
import os
import stat
import tempfile
from pathlib import Path
from typing import Any

import tomli_w

from .config import (
    DEFAULTS,
    _merge,
    config_from_dict,
    read_config_dict,
)

# Every editable setting: key -> expected type (nested dict = a TOML section).
SCHEMA: dict[str, Any] = {
    "username": str,
    "db_path": str,
    "user_agent": str,
    "reports_dir": str,
    "engine_path": str,
    "eval_ms": int,
    "eval_depth": int,
    "multipv": int,
    "threads": int,
    "hash_mb": int,
    "workers": int,
    "thresholds": {
        "brilliant": float,
        "best": float,
        "good": float,
        "inaccuracy": float,
        "mistake": float,
        "blunder": float,
    },
    "explorer": {
        "endpoint": str,
        "max_ply": int,
        "min_games": int,
        "top_moves": int,
        "delay_ms": int,
        "max_positions": int,
    },
    "opening": {
        "jobava_max_setup_ply": int,
        "caro_kann_max_ply": int,
    },
    "fetch": {
        "months": int,
        "since": str,
        "max_games": int,
    },
    "ui": {
        "default_time_class": str,
    },
}

TYPE_NAMES = {str: "string", int: "integer", float: "number"}


def schema_json(spec: dict[str, Any] | None = None) -> dict[str, Any]:
    """JSON-friendly view of the schema (type objects -> names), for the UI."""
    spec = SCHEMA if spec is None else spec
    return {
        key: schema_json(value) if isinstance(value, dict) else TYPE_NAMES[value]
        for key, value in spec.items()
    }


_HEADER = (
    "# chess-analysis configuration — generated by the web UI settings page.\n"
    "# Manual edits are welcome; the settings page rewrites this file.\n"
)


def _coerce(value: Any, expected: type, key: str) -> Any:
    """Form input arrives as strings; coerce to the schema type.

    JSON payloads may carry native numbers; the settings form sends strings.
    Non-numeric garbage, booleans, and inf/nan are all rejected with the
    offending key in the message.
    """
    if expected is str:
        if not isinstance(value, str):
            raise ValueError(f"{key}: expected a string")
        return value.strip()
    if isinstance(value, bool):
        raise ValueError(f"{key}: expected a number, got a boolean")
    if isinstance(value, (int, float)):
        f = float(value)
    else:
        try:
            f = float(str(value).strip())
        except ValueError:
            raise ValueError(f"{key}: expected a number") from None
    if not math.isfinite(f):
        raise ValueError(f"{key}: expected a finite number")
    if expected is float:
        return f
    i = int(f)
    if f != i:
        raise ValueError(f"{key}: expected an integer")
    return i


def _normalize(spec: dict[str, Any], payload: dict[str, Any], prefix: str) -> dict[str, Any]:
    """Keep only schema keys from payload, coerced; unknown keys are errors."""
    out: dict[str, Any] = {}
    for key, expected in spec.items():
        if key not in payload:
            continue
        value = payload[key]
        full = f"{prefix}{key}"
        if isinstance(expected, dict):
            if not isinstance(value, dict):
                raise ValueError(f"{full}: expected a table")
            out[key] = _normalize(expected, value, full + ".")
        elif value is None or (isinstance(value, str) and not value.strip()):
            # empty string / null clears a scalar; sections fall through above
            out[key] = "" if expected is str else 0
        else:
            out[key] = _coerce(value, expected, full)
    unknown = sorted(set(payload) - set(spec))
    if unknown:
        raise ValueError(f"unknown setting(s): {', '.join(unknown)}")
    return out


def settings_document(path: Path) -> dict[str, Any]:
    """Current values for the settings form: existing file merged over defaults."""
    return _merge(DEFAULTS, read_config_dict(path))


def update_settings(path: Path, payload: dict[str, Any]) -> dict[str, Any]:
    """Overlay a partial settings payload onto the current file and write it.

    Values the payload omits keep their current (file or default) values; when
    no file exists yet (the setup wizard), the new file is written complete,
    with every key at its default. Returns the document that was written.
    Raises ValueError with a user-presentable message on invalid input; the
    file is never touched then.
    """
    if not isinstance(payload, dict):
        raise ValueError("settings payload must be a JSON object")
    base = read_config_dict(path) or {k: dict(v) if isinstance(v, dict) else v for k, v in DEFAULTS.items()}
    clean = _normalize(SCHEMA, payload, "")
    doc = _merge(base, clean)
    # validate the full result before writing anything to disk
    config_from_dict(_merge(DEFAULTS, doc))
    write_config(path, doc)
    return doc


def write_config(path: Path, doc: dict[str, Any]) -> None:
    """Write the config document as TOML, atomically (tmp file + rename).

    The tmp file inherits the existing file's mode (host-owned files stay
    readable/writable for the host user); new files get 0644.
    """
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    data = _HEADER.encode("utf-8") + tomli_w.dumps(doc).encode("utf-8")
    fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=path.name, suffix=".tmp")
    try:
        try:
            mode = stat.S_IMODE(os.stat(path).st_mode)
        except OSError:
            mode = 0o644
        os.fchmod(fd, mode)
        with os.fdopen(fd, "wb") as f:
            f.write(data)
        os.replace(tmp, path)
    except BaseException:
        try:
            os.close(fd)
        except OSError:
            pass
        try:
            os.unlink(tmp)
        except OSError:
            pass
        raise
